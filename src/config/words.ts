export function generateWords(
  count: number,
  options?: { punctuation?: boolean; numbers?: boolean }
): string[] {
  const result: string[] = [];
  const punctuation = options?.punctuation ?? false;
  const numbers = options?.numbers ?? false;
  let capitalizeNext = false;

  for (let i = 0; i < count; i++) {
    // Replace ~10% of words with numbers if enabled
    if (numbers && Math.random() < 0.1) {
      result.push(String(Math.floor(Math.random() * 999) + 1));
      continue;
    }

    let word = englishWords[Math.floor(Math.random() * englishWords.length)];

    if (capitalizeNext) {
      word = word.charAt(0).toUpperCase() + word.slice(1);
      capitalizeNext = false;
    }

    if (punctuation && Math.random() < 0.1 && i < count - 1) {
      const punctMarks = ['.', ',', '?', '!', ';'];
      const mark = punctMarks[Math.floor(Math.random() * punctMarks.length)];
      word = word + mark;

      if (mark === '.' || mark === '?' || mark === '!') {
        capitalizeNext = true;
      }
    }

    result.push(word);
  }

  return result;
}

export function getRandomSentence(): string {
  return sentences[Math.floor(Math.random() * sentences.length)];
}

export function getQuote(length: 'short' | 'medium' | 'long'): string {
  const wordCounts = sentences.map((s) => ({
    sentence: s,
    words: s.split(' ').length,
  }));

  let filtered: typeof wordCounts;

  switch (length) {
    case 'short':
      filtered = wordCounts.filter((s) => s.words <= 20);
      break;
    case 'medium':
      filtered = wordCounts.filter((s) => s.words > 20 && s.words <= 30);
      break;
    case 'long':
      filtered = wordCounts.filter((s) => s.words > 30);
      break;
    default:
      filtered = wordCounts;
  }

  if (filtered.length === 0) {
    filtered = wordCounts;
  }

  return filtered[Math.floor(Math.random() * filtered.length)].sentence;
}
